#!/usr/bin/env python3
"""Generate ATF1508AS TQFP100 constraints from the intended pin plan.

The CSV is the assignment source; this does not infer wiring. Use --netlist
on a KiCad XML export to check whether its U1 wiring implements the plan.
"""
import argparse
import csv
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CORE = 'hp9835_unified_ram_rom_board'
TOP = CORE + '_pinned'
POWER = {3: '+5V', 18: '+5V', 34: '+5V', 51: '+5V', 66: '+5V',
         82: '+5V', 39: '+5V', 91: '+5V', 11: 'GND', 26: 'GND',
         38: 'GND', 43: 'GND', 59: 'GND', 74: 'GND', 86: 'GND', 95: 'GND'}
JTAG = {4: 'TDI', 15: 'TMS', 62: 'TCK', 73: 'TDO'}
DEDICATED = {87, 88, 89, 90}


def flat(signal):
    return signal.lower().replace('[', '_').replace(']', '')


def read_plan():
    source = (ROOT / 'logic' / (CORE + '.vhd')).read_text()
    source = re.sub(r'--[^\n]*', '', source)
    entity = re.search(r'entity\s+' + CORE + r'\s+is(.*?)end\s+entity', source,
                       flags=re.I | re.S).group(1)
    ports = {}
    for name, direction, high, low in re.findall(
            r'(\w+)\s*:\s*(inout|in|out)\s+std_logic(?:_vector\s*\(\s*(\d+)\s+downto\s+(\d+)\s*\))?',
            entity, flags=re.I):
        bits = [f'{name}[{i}]' for i in range(int(low), int(high)+1)] if high else [name]
        for bit in bits:
            ports[bit.upper()] = direction.lower()
    rows = list(csv.DictReader((ROOT / 'documentation/pin_plan.csv').open()))
    pins, mapped, assignments = set(), set(), []
    for row in rows:
        pin, signal = int(row['ATF1508_TQFP100_pin']), row['signal']
        if pin in pins or not 1 <= pin <= 100:
            raise ValueError(f'Duplicate/invalid pin {pin}')
        pins.add(pin)
        if pin in POWER:
            raise ValueError(f'Pin {pin} is a supply, not an assignable signal')
        if pin in JTAG:
            if signal != JTAG[pin]:
                raise ValueError(f'Pin {pin} is reserved for {JTAG[pin]}')
            continue
        if signal.startswith('SPARE') or signal == 'GCLR_N':
            continue
        if signal.upper() not in ports or signal.upper() in mapped:
            raise ValueError(f'Unknown/duplicate VHDL port {signal}')
        direction = ports[signal.upper()]
        expected_direction = {'in': 'IN', 'out': 'OUT', 'inout': 'BIDIR'}[direction]
        if row['direction'].split('-')[0] != expected_direction:
            raise ValueError(f'Wrong direction for {signal}')
        if pin in DEDICATED and direction != 'in':
            raise ValueError(f'Pin {pin} cannot drive {signal}')
        mapped.add(signal.upper())
        assignments.append((pin, signal, direction))
    if mapped != set(ports):
        raise ValueError(f'Missing VHDL ports: {set(ports)-mapped}')
    if not set(JTAG) <= pins:
        raise ValueError('Missing JTAG reservations')
    assigned = {s: p for p, s, _ in assignments}
    if assigned['HP_STM_N'] != 87 or assigned['HP_PH2'] != 90:
        raise ValueError('Clock assignments must use the planned global clock pins')
    return sorted(assignments)


def outputs(assignments):
    pin = f'CHIP "{TOP}" ASSIGNED TO AN TQFP100\n'
    pin += ''.join(f'{flat(signal):24s} : {number}\n' for number, signal, _ in assignments)
    declarations = ';\n'.join(f'        {flat(signal):24s} : {direction:5s} std_logic'
                                for _, signal, direction in assignments)
    # VHDL requires partial associations of a composite formal to be contiguous.
    association_order = sorted(assignments, key=lambda item: (
        item[1].split('[')[0], int(re.search(r'\[(\d+)\]', item[1])[1])
        if '[' in item[1] else -1))
    associations = ',\n'.join(
        f'            {signal.replace("[", "(").replace("]", ")"):24s} => {flat(signal)}'
        for _, signal, _ in association_order)
    wrapper = f'''-- Generated by tools/generate_cpld_constraints.py; edit the CSV pin plan.
-- Scalar top-level ports eliminate vector-index ambiguity in the fitter .pin file.
-- No JTAG ports: dedicated JTAG is selected by fitter options, not the VHDL core.
library ieee;
use ieee.std_logic_1164.all;

entity {TOP} is
    port (\n{declarations}\n    );
end entity;

architecture wiring of {TOP} is
begin
    core : entity work.{CORE}(rtl)
        port map (\n{associations}\n        );
end architecture;
'''
    return {ROOT / 'logic/constraints' / (TOP + '.pin'): pin,
            ROOT / 'logic' / (TOP + '.vhd'): wrapper}


def audit_netlist(path, assignments):
    root = ET.parse(path).getroot()
    actual = {}
    for net in root.findall('./nets/net'):
        for node in net.findall('node'):
            if node.get('ref') == 'U1':
                actual[int(node.get('pin'))] = net.get('name').lstrip('/')
    if not actual:
        raise ValueError('No U1 in supplied netlist')
    expected = dict(POWER)
    expected.update(JTAG)
    expected.update({p: s.replace('[', '').replace(']', '') for p, s, _ in assignments})
    # GCLR_N is not a core port; the existing plan calls for tying it inactive.
    expected[89] = '+5V'
    mismatches = [(p, value, actual.get(p, '<absent>')) for p, value in sorted(expected.items())
                  if actual.get(p) != value]
    for pin, expected_net, actual_net in mismatches:
        print(f'U1.{pin}: expected {expected_net}, actual {actual_net}')
    print(f'U1 netlist check: {len(mismatches)} mismatches / {len(expected)} checked pins')
    return not mismatches


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated files without writing')
    parser.add_argument('--netlist', type=Path, help='Also check U1 against a KiCad XML netlist')
    args = parser.parse_args()
    assignments = read_plan()
    for path, content in outputs(assignments).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise ValueError(f'Generated file is missing or stale: {path}')
        else:
            path.write_text(content)
    print(f'Validated {len(assignments)} scalar VHDL ports; no duplicate or reserved-pin assignments')
    if args.netlist and not audit_netlist(args.netlist, assignments):
        return 1
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError) as error:
        sys.exit(str(error))
